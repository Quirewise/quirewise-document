typedef struct Buffer {
    uint8_t *data;
    size_t size;
    size_t capacity;
} Buffer;

static int buffer_append(Buffer *buffer, const void *data, size_t size)
{
    if (buffer->size + size > buffer->capacity) {
        size_t capacity = buffer->capacity ? buffer->capacity : 4096u;
        uint8_t *grown;
        while (capacity < buffer->size + size) capacity *= 2u;
        grown = (uint8_t *)realloc(buffer->data, capacity);
        if (!grown) return 0;
        buffer->data = grown;
        buffer->capacity = capacity;
    }
    memcpy(buffer->data + buffer->size, data, size);
    buffer->size += size;
    return 1;
}

static int buffer_appendf(Buffer *buffer, const char *format, ...)
{
    char text[512];
    va_list args;
    int written;
    va_start(args, format);
    written = vsnprintf(text, sizeof(text), format, args);
    va_end(args);
    if (written < 0 || (size_t)written >= sizeof(text)) return 0;
    return buffer_append(buffer, text, (size_t)written);
}

static int build_pdf(Buffer *out, const uint8_t *image, size_t image_size,
                     int image_width, int image_height, int page_width,
                     int page_height, int draw_width, int draw_height,
                     const char *image_extra)
{
    size_t offsets[5];
    size_t index;
    size_t xref;
    char content[128];
    int content_size;
    content_size = snprintf(content, sizeof(content),
                            "q %d 0 0 %d 0 0 cm /Im0 Do Q", draw_width,
                            draw_height);
    if (content_size <= 0) return 0;
    memset(out, 0, sizeof(*out));
    if (!buffer_append(out, "%PDF-1.4\n", 9u)) return 0;
    offsets[0] = out->size;
    if (!buffer_appendf(out, "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n")) return 0;
    offsets[1] = out->size;
    if (!buffer_appendf(out, "2 0 obj\n<< /Type /Pages /Count 1 /Kids [3 0 R] >>\nendobj\n")) return 0;
    offsets[2] = out->size;
    if (!buffer_appendf(out,
                        "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 %d %d] "
                        "/Resources << /XObject << /Im0 5 0 R >> >> /Contents 4 0 R >>\nendobj\n",
                        page_width, page_height)) {
        return 0;
    }
    offsets[3] = out->size;
    if (!buffer_appendf(out, "4 0 obj\n<< /Length %d >>\nstream\n", content_size)) return 0;
    if (!buffer_append(out, content, (size_t)content_size)) return 0;
    if (!buffer_append(out, "\nendstream\nendobj\n", 18u)) return 0;
    offsets[4] = out->size;
    if (!buffer_appendf(out,
                        "5 0 obj\n<< /Type /XObject /Subtype /Image /Width %d /Height %d "
                        "/ColorSpace /DeviceGray %s /Length %zu >>\nstream\n",
                        image_width, image_height, image_extra, image_size)) {
        return 0;
    }
    if (!buffer_append(out, image, image_size)) return 0;
    if (!buffer_append(out, "\nendstream\nendobj\n", 18u)) return 0;
    xref = out->size;
    if (!buffer_appendf(out, "xref\n0 6\n0000000000 65535 f \n")) return 0;
    for (index = 0u; index < 5u; ++index) {
        if (!buffer_appendf(out, "%010zu 00000 n \n", offsets[index])) return 0;
    }
    if (!buffer_appendf(out, "trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n%zu\n%%%%EOF\n", xref)) {
        return 0;
    }
    return 1;
}

static int render_pdf(Buffer *pdf, unsigned dpi, QwPageImage *page)
{
    QwPdfDocument *document = NULL;
    size_t pages = 0u;
    QwConvertReport report;
    int ok = 0;
    memset(&report, 0, sizeof(report));
    memset(page, 0, sizeof(*page));
    if (qw_pdf_open(pdf->data, pdf->size, &document, &pages, &report) != QW_STATUS_OK ||
        !document || pages != 1u) {
        return 0;
    }
    if (qw_pdf_render_page(document, 0u, dpi, page, &report) == QW_STATUS_OK) {
        ok = 1;
    }
    qw_pdf_close(document);
    return ok;
}

static int bit_at(const uint8_t *bits, uint32_t x, uint32_t y)
{
    return (bits[(size_t)y * (JB2_WIDTH / 8u) + (x >> 3)] >> (7u - (x & 7u))) & 1;
}

static void test_arithmetic_region(void)
{
    Buffer pdf;
    QwPageImage page;
    uint32_t x;
    uint32_t y;
    int mismatches = 0;
    CHECK(build_pdf(&pdf, kJbig2Stream, sizeof(kJbig2Stream),
                    (int)JB2_WIDTH, (int)JB2_HEIGHT, (int)JB2_WIDTH,
                    (int)JB2_HEIGHT, (int)JB2_WIDTH, (int)JB2_HEIGHT,
                    "/BitsPerComponent 1 /Filter /JBIG2Decode") == 1);
    if (!render_pdf(&pdf, 72u, &page)) {
        fputs("arithmetic JBIG2: render failed\n", stderr);
        ++g_failures;
        free(pdf.data);
        return;
    }
    CHECK(page.width == JB2_WIDTH);
    CHECK(page.height == JB2_HEIGHT);
    if (page.data && page.width == JB2_WIDTH && page.height == JB2_HEIGHT &&
        page.kind == QW_PAGE_IMAGE_RGB24) {
        for (y = 0u; y < JB2_HEIGHT; ++y) {
            for (x = 0u; x < JB2_WIDTH; ++x) {
                const uint8_t *pixel = page.data + ((size_t)y * page.width + x) * 3u;
                int dark = pixel[0] < 128;
                if (dark != (bit_at(kExpectedBits, x, y) != 0)) {
                    if (mismatches < 6) {
                        fprintf(stderr, "arithmetic JBIG2: pixel %u,%u dark=%d\n",
                                x, y, dark);
                    }
                    ++mismatches;
                }
            }
        }
        if (mismatches) {
            fprintf(stderr, "arithmetic JBIG2: %d mismatched pixels\n", mismatches);
            ++g_failures;
        }
    } else {
        fputs("arithmetic JBIG2: unexpected output format\n", stderr);
        ++g_failures;
    }
    qw_pdf_page_free(&page);
    free(pdf.data);
}

static void test_render_resolution(void)
{
    /* 8x8 grey image drawn onto a 72x72 point page; at 144 dpi the page is
     * 144x144 pixels and the image must fill it. */
    Buffer pdf;
    QwPageImage page;
    uint8_t image[64];
    size_t i;
    for (i = 0u; i < sizeof(image); ++i) image[i] = 32u;
    CHECK(build_pdf(&pdf, image, sizeof(image), 8, 8, 72, 72, 72, 72,
                    "/BitsPerComponent 8") == 1);
    if (!render_pdf(&pdf, 144u, &page)) {
        fputs("render resolution: render failed\n", stderr);
        ++g_failures;
        free(pdf.data);
        return;
    }
    CHECK(page.width == 144u);
    CHECK(page.height == 144u);
    if (page.data && page.width == 144u && page.height == 144u) {
        const uint8_t *corner = page.data;
        const uint8_t *centre = page.data +
            ((size_t)72u * page.width + 72u) * 3u;
        CHECK(corner[0] < 128);
        CHECK(centre[0] < 128);
        CHECK(page.data[((size_t)143u * page.width + 143u) * 3u] < 128);
    }
    qw_pdf_page_free(&page);
    free(pdf.data);
}

int main(void)
{
    test_arithmetic_region();
    test_render_resolution();
    if (g_failures) {
        fprintf(stderr, "%d check(s) failed\n", g_failures);
        return 1;
    }
    puts("PASS: JBIG2 arithmetic regions and render resolution");
    return 0;
}
